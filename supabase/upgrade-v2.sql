-- Replace owner-only policies with workspace-aware policies.
do $$ declare t text; begin
  foreach t in array array['clients','sales','payments','expenses','goals','budgets'] loop
    execute format('drop policy if exists %I on public.%I',t||'_own',t);
    execute format('drop policy if exists %I on public.%I',t||'_view',t);
    execute format('drop policy if exists %I on public.%I',t||'_insert',t);
    execute format('drop policy if exists %I on public.%I',t||'_update',t);
    execute format('drop policy if exists %I on public.%I',t||'_delete',t);
    execute format('create policy %I on public.%I for select using (public.can_view_workspace(workspace_id))',t||'_view',t);
    execute format('create policy %I on public.%I for insert with check (public.can_edit_workspace(workspace_id))',t||'_insert',t);
    execute format('create policy %I on public.%I for update using (public.can_edit_workspace(workspace_id)) with check (public.can_edit_workspace(workspace_id))',t||'_update',t);
    execute format('create policy %I on public.%I for delete using (public.can_edit_workspace(workspace_id))',t||'_delete',t);
  end loop;
end $$;

drop policy if exists workspaces_view on public.workspaces; create policy workspaces_view on public.workspaces for select using(public.can_view_workspace(id));
drop policy if exists workspaces_update on public.workspaces; create policy workspaces_update on public.workspaces for update using(public.can_manage_workspace(id));
drop policy if exists members_view on public.workspace_members; create policy members_view on public.workspace_members for select using(public.can_view_workspace(workspace_id));
drop policy if exists members_manage on public.workspace_members; create policy members_manage on public.workspace_members for all using(public.can_manage_workspace(workspace_id)) with check(public.can_manage_workspace(workspace_id));
drop policy if exists invites_manage on public.workspace_invitations; create policy invites_manage on public.workspace_invitations for all using(public.can_manage_workspace(workspace_id)) with check(public.can_manage_workspace(workspace_id));

do $$ declare t text; begin
  foreach t in array array['categories','sale_templates','recurring_rules'] loop
    execute format('drop policy if exists %I on public.%I',t||'_view',t);
    execute format('drop policy if exists %I on public.%I',t||'_manage',t);
    execute format('create policy %I on public.%I for select using (public.can_view_workspace(workspace_id))',t||'_view',t);
    execute format('create policy %I on public.%I for all using (public.can_edit_workspace(workspace_id)) with check (public.can_edit_workspace(workspace_id))',t||'_manage',t);
  end loop;
end $$;

