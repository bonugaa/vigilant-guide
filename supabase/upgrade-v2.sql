create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null default 'Mi espacio Clario',
  created_at timestamptz not null default now()
);

create table if not exists public.workspace_members (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','editor','viewer')),
  display_name text not null default '', email text not null default '',
  created_at timestamptz not null default now(),
  unique(workspace_id,user_id)
);

create table if not exists public.workspace_invitations (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  email text not null, role text not null check (role in ('editor','viewer')),
  token uuid not null default gen_random_uuid() unique,
  invited_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  accepted_at timestamptz, created_at timestamptz not null default now()
);

create or replace function public.workspace_role(p_workspace uuid) returns text
language sql stable security definer set search_path=public as $$
  select role from public.workspace_members where workspace_id=p_workspace and user_id=auth.uid() limit 1
$$;
create or replace function public.can_view_workspace(p_workspace uuid) returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.workspace_members where workspace_id=p_workspace and user_id=auth.uid())
$$;
create or replace function public.can_edit_workspace(p_workspace uuid) returns boolean
language sql stable security definer set search_path=public as $$
  select coalesce(public.workspace_role(p_workspace) in ('owner','editor'),false)
$$;
create or replace function public.can_manage_workspace(p_workspace uuid) returns boolean
language sql stable security definer set search_path=public as $$
  select coalesce(public.workspace_role(p_workspace)='owner',false)
$$;
create or replace function public.current_workspace_id() returns uuid
language sql stable security definer set search_path=public as $$
  select coalesce(
    (select active_workspace_id from public.profiles where id=auth.uid()),
    (select workspace_id from public.workspace_members where user_id=auth.uid() order by created_at limit 1)
  )
$$;

insert into public.workspaces(owner_id,name)
select p.id,case when coalesce(p.name,'')='' then 'Mi espacio Clario' else 'Clario de '||p.name end
from public.profiles p where not exists(select 1 from public.workspaces w where w.owner_id=p.id);
insert into public.workspace_members(workspace_id,user_id,role,display_name,email)
select w.id,w.owner_id,'owner',coalesce(p.name,''),coalesce(p.email,u.email,'')
from public.workspaces w left join public.profiles p on p.id=w.owner_id left join auth.users u on u.id=w.owner_id
on conflict(workspace_id,user_id) do update set role='owner';
update public.profiles p set email=coalesce(nullif(p.email,''),u.email,''),active_workspace_id=coalesce(p.active_workspace_id,w.id)
from auth.users u,public.workspaces w where u.id=p.id and w.owner_id=p.id;

