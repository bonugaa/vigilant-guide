create or replace function public.reset_active_workspace_after_member_delete() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if (select active_workspace_id from public.profiles where id=old.user_id)=old.workspace_id then
    update public.profiles set active_workspace_id=(select workspace_id from public.workspace_members where user_id=old.user_id order by created_at limit 1) where id=old.user_id;
  end if;
  return old;
end $$;
drop trigger if exists on_workspace_member_deleted on public.workspace_members;
create trigger on_workspace_member_deleted after delete on public.workspace_members for each row execute function public.reset_active_workspace_after_member_delete();

create or replace function public.accept_workspace_invite(p_token uuid) returns uuid
language plpgsql security definer set search_path=public as $$
declare v_inv public.workspace_invitations; v_name text; v_email text;
begin
  select * into v_inv from public.workspace_invitations where token=p_token and accepted_at is null;
  if v_inv.id is null then raise exception 'INVITE_NOT_FOUND'; end if;
  select coalesce(raw_user_meta_data->>'name',''),coalesce(email,'') into v_name,v_email from auth.users where id=auth.uid();
  if lower(v_email)<>lower(v_inv.email) then raise exception 'INVITE_EMAIL_MISMATCH'; end if;
  insert into public.workspace_members(workspace_id,user_id,role,display_name,email)
  values(v_inv.workspace_id,auth.uid(),v_inv.role,v_name,v_email)
  on conflict(workspace_id,user_id) do update set role=excluded.role,display_name=excluded.display_name,email=excluded.email;
  update public.workspace_invitations set accepted_at=now() where id=v_inv.id;
  update public.profiles set active_workspace_id=v_inv.workspace_id where id=auth.uid();
  return v_inv.workspace_id;
end $$;

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
declare v_workspace uuid;
begin
  insert into public.profiles(id,name,email) values(new.id,coalesce(new.raw_user_meta_data->>'name',''),coalesce(new.email,'')) on conflict(id) do update set email=excluded.email;
  insert into public.workspaces(owner_id,name) values(new.id,'Clario de '||coalesce(nullif(new.raw_user_meta_data->>'name',''),'Usuario')) returning id into v_workspace;
  insert into public.workspace_members(workspace_id,user_id,role,display_name,email) values(v_workspace,new.id,'owner',coalesce(new.raw_user_meta_data->>'name',''),coalesce(new.email,''));
  update public.profiles set active_workspace_id=v_workspace where id=new.id;
  insert into public.categories(workspace_id,type,name) values
   (v_workspace,'business','Suscripciones'),(v_workspace,'business','Fotografía'),(v_workspace,'business','Impresión QR'),
   (v_workspace,'business','Equipamiento'),(v_workspace,'business','Marketing'),(v_workspace,'business','Otros'),
   (v_workspace,'personal','Comida'),(v_workspace,'personal','Ropa'),(v_workspace,'personal','Deporte'),
   (v_workspace,'personal','Zapatillas'),(v_workspace,'personal','Ocio y lujos'),(v_workspace,'personal','Transporte'),(v_workspace,'personal','Otros');
  return new;
end $$;

