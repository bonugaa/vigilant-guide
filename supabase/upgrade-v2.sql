create table if not exists public.recurring_rules (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default public.current_workspace_id() references public.workspaces(id) on delete cascade,
  name text not null, amount numeric(12,2) not null check(amount>0),
  type text not null check(type in ('business','personal')), category text not null, subcategory text default '',
  method text not null default 'Tarjeta', deductible boolean not null default false, description text default '',
  frequency text not null default 'monthly' check(frequency in ('monthly','yearly')),
  next_due date not null, active boolean not null default true, created_at timestamptz not null default now()
);

